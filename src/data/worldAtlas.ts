export interface AtlasFilters {
  searchQuery: string;
  category?: WorldCategoryType | 'ALL';
  rightsStatus?: RightsStatusType | 'ALL';
  medium: MediumType | 'ALL';
  primaryFantasy: PrimaryFantasyType | 'ALL';
  audienceScale: AudienceScaleType | 'ALL';
  goldenOnly?: boolean;
  benchmarkOnly?: boolean;
  minCulturalFamiliarity: number;
  sortBy: 'familiarity' | 'overallScore' | 'name' | 'agency' | 'simulationDepth';
}

export function filterWorldAtlas(
  entries: WorldAtlasEntry[],
  filters: AtlasFilters
): WorldAtlasEntry[] {
  return entries.filter(entry => {
    // Search query
    if (filters.searchQuery.trim()) {
      const q = filters.searchQuery.toLowerCase();
      const matchName = entry.name.toLowerCase().includes(q);
      const matchSource = entry.sourceOrOrigin.toLowerCase().includes(q);
      const matchSetting = entry.setting.toLowerCase().includes(q);
      const matchGenre = entry.genre.some(g => g.toLowerCase().includes(q));
      const matchRole = entry.inhabitedExperience.primaryRoleInhabited.toLowerCase().includes(q);
      if (!matchName && !matchSource && !matchSetting && !matchGenre && !matchRole) {
        return false;
      }
    }

    // Category
    if (filters.category && filters.category !== 'ALL') {
      const entryCategory = entry.worldCategory || (
        entry.medium === 'Historical & Real-World' ? 'Historical World' :
        entry.medium === 'Philosophical & Concept' ? 'Original Archetype' : 'Fictional IP'
      );
      if (entryCategory !== filters.category) return false;
    }

    // Rights Status
    if (filters.rightsStatus && filters.rightsStatus !== 'ALL') {
      const entryRights = entry.rightsStatus || (
        entry.medium === 'Historical & Real-World' ? 'historical_real_world' :
        entry.medium === 'Philosophical & Concept' ? 'original_archetype' : 'licensed_required'
      );
      if (entryRights !== filters.rightsStatus) return false;
    }

    // Golden Only
    if (filters.goldenOnly && !entry.isGoldenWorld) {
      // Check if it's one of the 12 golden world IDs
      const goldenIds = [
        'atlas-spy-family', 'atlas-hogwarts', 'atlas-sherlock', 'atlas-got',
        'atlas-cyberpunk-edge', 'atlas-outer-wilds', 'atlas-ancient-rome',
        'atlas-heian-kyoto', 'atlas-elite-university', 'atlas-silicon-valley-1999',
        'atlas-disco-elysium', 'atlas-papers-please'
      ];
      if (!goldenIds.includes(entry.id)) return false;
    }

    // Benchmark Only
    if (filters.benchmarkOnly && !entry.isBenchmarkWorld && !['atlas-spy-family', 'atlas-got', 'atlas-outer-wilds', 'atlas-sherlock'].includes(entry.id)) {
      return false;
    }

    // Medium
    if (filters.medium !== 'ALL' && entry.medium !== filters.medium) {
      return false;
    }

    // Primary Fantasy
    if (filters.primaryFantasy !== 'ALL' && entry.fantasyProfile.primary !== filters.primaryFantasy) {
      return false;
    }

    // Audience Scale
    if (filters.audienceScale !== 'ALL' && entry.audienceScale !== filters.audienceScale) {
      return false;
    }

    // Min Familiarity
    if (entry.culturalFamiliarity < filters.minCulturalFamiliarity) {
      return false;
    }

    return true;
  }).sort((a, b) => {
    if (filters.sortBy === 'familiarity') return b.culturalFamiliarity - a.culturalFamiliarity;
    if (filters.sortBy === 'overallScore') return b.headConanPotential.overallScore - a.headConanPotential.overallScore;
    if (filters.sortBy === 'agency') return b.interactionProfile.agency - a.interactionProfile.agency;
    if (filters.sortBy === 'simulationDepth') return b.interactionProfile.simulationDepth - a.interactionProfile.simulationDepth;
    return a.name.localeCompare(b.name);
  });
}
