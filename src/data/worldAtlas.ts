export type WorldCategoryType = 
  | 'Fictional IP'
  | 'Historical World'
  | 'Real-World / Life World'
  | 'Original Archetype';

export type RightsStatusType =
  | 'public_domain'
  | 'historical_real_world'
  | 'original_archetype'
  | 'licensed_required'
  | 'unclear';

export type MediumType = 
  | 'Literature'
  | 'Cinema & TV'
  | 'Anime & Manga'
  | 'Gaming'
  | 'Historical & Real-World'
  | 'Mythology & Folklore'
  | 'Philosophical & Concept';

export type AudienceScaleType = 
  | 'Universal Archetype'
  | 'Global Mega-IP'
  | 'Broad Cult Favorite'
  | 'Niche High-Engagement';

export type PrimaryFantasyType =
  | 'Identity'
  | 'Power'
  | 'Social'
  | 'Relationship'
  | 'Exploration'
  | 'Mystery & Knowledge'
  | 'Survival'
  | 'Creation & System'
  | 'Political & Intrigue'
  | 'Life & Path'
  | 'Transformation & Causality';

export interface WorldAtlasEntry {
  id: string;
  name: string;
  sourceOrOrigin: string;
  worldCategory?: WorldCategoryType;
  rightsStatus?: RightsStatusType;
  isGoldenWorld?: boolean;
  isBenchmarkWorld?: boolean;
  benchmarkType?: 'SOCIAL' | 'POLITICAL' | 'EXPLORATION' | 'MYSTERY';
  productHypothesis?: string;
  medium: MediumType;
  genre: string[];
  setting: string;
  era: string;
  culturalFamiliarity: number; // 1-100
  audienceScale: AudienceScaleType;

  // Fantasy Profile (Scores 1 to 5)
  fantasyProfile: {
    primary: PrimaryFantasyType;
    secondary: PrimaryFantasyType;
    identity: number;       // "I want to become someone else"
    power: number;          // "I want extraordinary power/mastery"
    social: number;         // "I want to live among fascinating people"
    relationship: number;   // "I want deep bonds/rivalries/romances"
    exploration: number;    // "I want to discover an awe-inspiring world"
    mystery: number;        // "I want to uncover secrets and truth"
    creation: number;       // "I want to build/govern an organization"
    survival: number;       // "I want to endure extreme circumstances"
    transformation: number; // "I want to test alternate paths/causes"
  };

  // Interaction Profile (Scores 1 to 5)
  interactionProfile: {
    agency: number;          // Degree of player freedom
    socialDensity: number;   // Intensity of character/dialogue web
    exploration: number;     // Spatial & lore discovery depth
    conflict: number;        // Tension / stakes level
    discovery: number;       // Uncovering concealed information
    simulationDepth: number; // Systemic cause-and-effect rules
    roleDiversity: number;   // Variety of compelling roles
  };

  // HeadConan Potential (Scores 1 to 5)
  headConanPotential: {
    overallScore: number;          // Derived score
    adaptationPotential: number;   // Feasibility without rigid 3D assets
    showcasePotential: number;     // "Aha!" moment for new users
    replayability: number;         // Replay value across turns/roles
    ugcScenarioPotential: number;  // Potential for community forks
    worldRuntimePotential: number; // Natural fit with LLM + state machine
    generativeUiPotential: number; // How distinct the UI layout can be
  };

  // Inhabited Experience Definition
  inhabitedExperience: {
    primaryRoleInhabited: string;
    alternativeRoles: string[];
    coreExperientialLoop: string;
    whyInhabitedNotWatched: string;
    uiArchetypeSuitability: string;
    keyFactionsOrEntities: string[];
  };

  notes: string;
}

